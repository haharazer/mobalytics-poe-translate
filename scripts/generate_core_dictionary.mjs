import fs from "node:fs/promises";
import path from "node:path";
import { readDomain, projectNames, projectAffixNames, readSkillDescriptions, compactEntries } from "./lib/client-data.mjs";

// Explicit inputs: no temporary-directory scan or automatic release fallback.
const clientRoot = process.env.POE_CLIENT_DATA_ROOT ?? "C:/Users/hanpe/Desktop/poe-client-data";
const options = {
  names: path.join(clientRoot, "dist/current/domains/localized-names/localized-names.v1.manifest.json"),
  affixes: path.join(clientRoot, "dist/demo/domains/affixes/affixes.v1.manifest.json"),
  "skill-tables": path.join(clientRoot, "work/localized-names-csv"),
  output: "data/poe1-core.js", report: "data/poe1-core.report.json"
};
for (let i = 2; i < process.argv.length; i += 2) {
  const key = process.argv[i].replace(/^--/, "");
  if (!(key in options) || !process.argv[i + 1]) throw new Error(`Unknown or missing option: ${process.argv[i]}`);
  options[key] = process.argv[i + 1];
}
const names = await readDomain(options.names);
const affixes = await readDomain(options.affixes);
const descriptions = await readSkillDescriptions(names.manifest, options["skill-tables"]);
const entries = compactEntries([
  ...projectNames(names.records, ["item", "passive"]),
  ...projectAffixNames(affixes.records),
  ...descriptions.entries
]);
const counts = Object.fromEntries(["item", "passive", "affix", "skillDescription"].map(
  (category) => [category, entries.filter((entry) => entry.category === category).length]
));
const collisions = [], byName = new Map();
for (const entry of entries) {
  const key = `${entry.category}:${entry.en.replace(/\s+/g, " ").trim()}`;
  if (!byName.has(key)) byName.set(key, []);
  byName.get(key).push(entry);
}
for (const [key, candidates] of byName) {
  if (candidates.length > 1) collisions.push({ key, candidates });
}
const source = ({ manifest }) => ({
  datasetId: manifest.dataset_id, artifact: manifest.artifact, source: manifest.source
});
const report = {
  schemaVersion: 1,
  sources: { names: source(names), affixes: source(affixes), skillDescriptionInputs: descriptions.inputs },
  counts,
  missingLocales: {
    zhCN: entries.filter((entry) => !entry.zhCN).length,
    zhTW: entries.filter((entry) => !entry.zhTW).length
  },
  collisions,
  limitations: [
    "item covers BaseItemTypes, not resolved unique item names",
    "passive covers names, not stat effects or mastery options",
    "affix covers Mods.Name, not formatted stat descriptions",
    "skillDescription uses a transitional hash-checked ActiveSkills.Description input adapter, not a released localized-text contract",
    "client versions differ; source versions and input hashes are retained above",
    "markup-bearing descriptions are skipped; missing locales remain untranslated"
  ]
};
const body = `/* Generated by scripts/generate_core_dictionary.mjs. */\n` +
  `(function registerPoe1Core(global) {\n` +
  `  global.POE1_CORE = Object.freeze({\n` +
  `    counts: Object.freeze(${JSON.stringify(counts)}),\n` +
  `    entries: Object.freeze(${JSON.stringify(entries)}.map((entry) => Object.freeze(entry)))\n` +
  `  });\n})(typeof globalThis !== "undefined" ? globalThis : this);\n`;
for (const [file, content] of [[options.output, body], [options.report, JSON.stringify(report, null, 2) + "\n"]]) {
  await fs.mkdir(path.dirname(file), { recursive: true });
  await fs.writeFile(file, content, "utf8");
}
console.log(`Core dictionary: ${JSON.stringify(counts)}; ${collisions.length} collision groups retained for safe runtime resolution.`);
